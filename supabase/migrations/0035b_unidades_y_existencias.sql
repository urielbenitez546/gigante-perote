-- 1) Función que decide la unidad por el nombre
create or replace function public.clasificar_unidad(p_nombre text, p_total numeric default null)
returns product_unit
language sql
immutable
as $fn$
  select (case
    when p_nombre ~* '\(\s*caja\s+(con|c/)' then 'caja'
    when p_nombre ~* '(pega|adhesivo|junteador|boquilla|cemento|mortero|\ykg\y|sellador|impermeab)'
         and p_nombre !~ '^\s*\d+(\.\d+)?\s*[xX]\s*\d+' then 'bolsa'
    when p_nombre ~* '(lavabo|decorado|mural|cenefa|uniperfil|wpc|lamina|lámina|panel|espejo|tarja|fregadero|mezcl|monomando|regadera|tinaco|cisterna|calentador|perfil|moldura|zoclo|zócalo|toallero|gancho|jabonera|esquinero|llave|tubo|manguera|tanque|inodoro|w\.?c\y|asiento|bote|accesorio|válvula|valvula|coladera|rejilla|desague|paquete|kit|base|pedestal|anafre|cubierta|relieve|listelo|vitropiedra|charola|rodapi|boquilla|trim)'
      then 'pieza'
    when p_nombre ~ '^\s*\d+(\.\d+)?\s*[xX]\s*\d+'
         or p_nombre ~* 'm2\y'
         or (p_total is not null and p_total <> trunc(p_total)) then 'm2'
    else 'pieza'
  end)::product_unit
$fn$;

-- Productos nuevos: si no se les pone unidad, se clasifican solos.
create or replace function public.productos_unidad_automatica()
returns trigger
language plpgsql
as $fn$
begin
  if new.unit = 'caja' then
    new.unit := public.clasificar_unidad(new.name);
  end if;
  return new;
end;
$fn$;

