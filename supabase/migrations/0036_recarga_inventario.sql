  -- 2) Crear los que faltan
  for r in select * from _lista order by ext::numeric loop
    if exists (select 1 from public.products where external_id::text = r.ext) then
      continue;
    end if;
    v_codigo := r.codigo;
    if exists (select 1 from public.products where code = v_codigo) then
      v_codigo := 'SIGAM-' || r.ext;
    end if;
    v_unidad := coalesce(nullif(r.unidad, ''), public.clasificar_unidad(r.nombre, r.total)::text);

    execute format(
      $q$insert into public.products
           (code, name, brand, category, unit, physical_stock, sold_pending, external_id, rotacion, active, last_counted_at)
         values
           (%L, %L, %L,
            coalesce((select p.category from public.products p where p.brand = %L
                       group by p.category order by count(*) desc limit 1), 'Sin categoría'),
            %L, %s, 0, %L, 'incorporacion', true, now())$q$,
      v_codigo, r.nombre, r.marca, r.marca, v_unidad, r.total, r.ext);
    get diagnostics n_fila = row_count;
    if n_fila > 0 then
      n_creados := n_creados + 1;
      ids_creados := ids_creados || ' ' || r.ext;
    end if;
